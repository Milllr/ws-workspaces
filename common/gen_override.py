#!/usr/bin/env python3
"""Generate a Compose override that fully isolates one worktree's Docker stack.

Namespaces every service's container_name and offsets its published host ports,
so several workspaces can `make run` concurrently without colliding. Emits
`<base>.override.<ext>` next to the base compose file; Compose auto-merges it.
Uses the `!override` tag so offset ports REPLACE (not append to) the base ports.

Invoked by `ws -d`.  Touches no tracked repo files.

argv: <compose_path> <workspace_name> <slot 0=auto|1..5> [project_name]
stdout: line1=override filename, line2=project name, rest="port <svc> <old> <new>"
"""
import sys
import zlib
from pathlib import Path

try:
    import yaml
except ImportError:
    sys.stderr.write(
        f"ws -d: PyYAML not available in {sys.executable} — `pip install pyyaml` "
        "or run ws -d from a python env that has it.\n"
    )
    sys.exit(3)

MAX_SLOTS = 5          # slot*10000 keeps 8000 -> max 58000 (< 65535)
SLOT_STEP = 10000


def offset_port(entry, off):
    """Offset the *host* port of a compose ports entry, leaving target/proto/ip."""
    if isinstance(entry, dict):
        e = dict(entry)
        if e.get("published") is not None:
            e["published"] = int(e["published"]) + off
        return e
    s = str(entry)
    proto = ""
    if "/" in s:
        s, proto = s.split("/", 1)
        proto = "/" + proto
    parts = s.split(":")            # [host,target] or [ip,host,target]
    if len(parts) >= 2 and parts[-2].isdigit():
        parts[-2] = str(int(parts[-2]) + off)
        return ":".join(parts) + proto
    return str(entry)              # unpublished / unparseable -> leave as-is


def main():
    compose_path = Path(sys.argv[1])
    ws = sys.argv[2]
    slot_arg = int(sys.argv[3]) if len(sys.argv) > 3 and sys.argv[3].isdigit() else 0
    project = sys.argv[4] if len(sys.argv) > 4 else compose_path.parent.name

    slot = slot_arg if 1 <= slot_arg <= MAX_SLOTS else (zlib.crc32(ws.encode()) % MAX_SLOTS) + 1
    off = slot * SLOT_STEP

    data = yaml.safe_load(compose_path.read_text()) or {}
    services = data.get("services", {}) or {}

    out = [
        "# AUTO-GENERATED by `ws -d` — safe to delete, do not edit by hand.",
        f"# workspace={ws}  slot={slot}  host-port-offset=+{off}",
        f"name: {project}-{ws}",
        "services:",
    ]
    portmap = []
    for svc, body in services.items():
        body = body or {}
        out.append(f"  {svc}:")
        out.append(f"    container_name: {(body.get('container_name') or svc)}-{ws}")
        ports = body.get("ports")
        if ports:
            out.append("    ports: !override")
            for op in ports:
                np = offset_port(op, off)
                np_s = f"{np['published']}:{np['target']}" if isinstance(np, dict) else str(np)
                out.append(f'      - "{np_s}"')
                portmap.append((svc, str(op), np_s))

    override_name = f"{compose_path.stem}.override{compose_path.suffix}"
    (compose_path.parent / override_name).write_text("\n".join(out) + "\n")

    print(override_name)
    print(f"{project}-{ws}")
    for svc, op, np in portmap:
        print(f"port {svc} {op} -> {np}")


if __name__ == "__main__":
    main()
